#!/usr/bin/env python3
"""Общее правило «это товар, а не сопутствующее».

Живёт отдельным модулем, потому что им пользуются двое: страница каталога
и данные квиза. Разъедься они — и счётчик в квизе начнёт обещать позиции,
которых в каталоге нет, а мы обещаем, что число честное.
"""
import re

# Сопутствующее — не покрытие. Сортировка в каталоге идёт по цене, и без этого
# страница открывается четырьмя листами подложки: они просто самые дешёвые.
EXCLUDE_GROUPS = {"Подложка и комплектующие"}

# Часть сопутствующего лежит прямо в товарных группах — это грязь в выгрузке,
# а не наша ошибка (вопрос по каталогу к клиенту). Отсекаем по названию.
#
# У плитки то же самое, что у подложки в ламинате, только заметнее: сортировка
# по цене поднимала наверх клинья по 78 ₽, затирки и клей — 8 таких позиций
# в первой сотне. Человек, пришедший по объявлению «керамогранит», видел
# сверху мешок клея. В квизе те же позиции роняли нижнюю границу расчёта:
# клин за 78 ₽ попадал в 25-й процентиль как «плитка от 78 ₽/м²».
#
# «Клин» и «клинкер» — разные вещи: клинкер это плитка, и словоформы разведены
# границей слова. Проверено на выгрузке: фильтр берёт 13 позиций в плитке
# и ни одной в полах.
EXCLUDE_NAME = re.compile(
    r"^\s*(?:подложк|затирк|клей\b|клеевая|грунтовк|грунт\b|герметик|"
    r"крестик|клин\s|клин\b|система выравн|СВП\b|уголок|профиль|"
    r"мастик|гидроизол|штукатурк|шпаклевк|смесь\b|наливной пол|плиточный)",
    re.IGNORECASE,
)


def is_product(item: dict) -> bool:
    """Товар ли это с точки зрения рекламы — или мешок клея рядом с ним."""
    return (
        item["group"] not in EXCLUDE_GROUPS
        and not EXCLUDE_NAME.match(item["name"])
    )


def drop_piece_decor(items: list) -> list:
    """Убирает штучный декор, который в списке по цене выглядит как дешёвая плитка.

    Первым в каталоге плитки стоял «Octagon Taco 4,6×4,6» за 54 ₽ — вставка
    между плитками, а человек читает первую строку как «керамогранит от 54 ₽».
    Порог не выдумываем, а берём из самих данных: дешевле самой дешёвой
    метровой позиции направления цена за метр быть не может.

    Применяют и каталог, и данные квиза — иначе счётчик обещает позиции,
    которых в каталоге нет.
    """
    metre_prices = [i["price"] for i in items if i["unit"] == "м²"]
    if not metre_prices:
        return items
    floor = min(metre_prices)
    return [i for i in items if i["unit"] == "м²" or i["price"] >= floor]
